/** Escapes text for use inside HTML (e-mail templates). */
export function escapeHtml(value: string | number | null | undefined): string {
  return `${value ?? ''}`
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
